"""Cleaned data pack as an Excel workbook."""
import io
from datetime import datetime, timezone

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from .core import Dataset
from .reference import LABEL, VALUE_FIELDS

HEAD = PatternFill("solid", fgColor="17644A")


def _sheet(wb, title, head, rows, widths=None):
    ws = wb.create_sheet(title)
    ws.append(head)
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = HEAD
        c.alignment = Alignment(vertical="top", wrap_text=True)
    for r in rows:
        ws.append(["" if v is None else v for v in r])
    for i, h in enumerate(head, 1):
        longest = max([len(str(h))] + [len(str(r[i - 1] or "")) for r in rows[:200]])
        w = (widths or {}).get(h) or min(60, max(10, longest + 2))
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    if rows:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(head))}{len(rows) + 1}"
    return ws


def data_pack(ds: Dataset, assess: dict | None, clean: dict | None, user: str, ctx: dict | None = None) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "README"
    for row in [
        ["Data360 data pack", ds.borrower],
        ["Version", ds.version],
        ["Generated", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")],
        ["Generated by", user],
        ["Reference date", ds.ref_date.isoformat()],
        ["Records", len(ds.live())],
        ["Internal elements", len(ds.live_elements())],
        ["Data confidence", f"{assess['overall']['score']}/100 ({assess['overall']['rating']})" if assess else "Assess not run"],
        ["Note", "Prepared from the uploaded source files. Values marked golden follow the survivorship rules in the Golden record sheet."],
    ]:
        ws.append(row)
    ws.column_dimensions["A"].width = 22
    ws.column_dimensions["B"].width = 90
    for c in ws["A"]:
        c.font = Font(bold=True)

    G = clean["golden"] if clean else (assess or {}).get("golden", {})
    _sheet(wb, "Golden record", ["Field", "Golden value", "Source", "Record", "As of", "Rule", "Why", "Agreeing sources"],
           [[LABEL[f], g["display"], g["source"], g["record"], g["as_of"], g["rule"], g["why"], ", ".join(g["support"])] if g
            else [LABEL[f], "Not held", "", "", "", "", "", ""] for f, g in G.items()])
    _sheet(wb, "Records", ["Record", "Source", "Zone", "As of", "Status", *[LABEL[f] for f in VALUE_FIELDS]],
           [[r.rid, r.source, r.zone, r.as_of.isoformat() if r.as_of else "", r.status or r.flag, *[r.fields.get(f) for f in VALUE_FIELDS]]
            for r in ds.live()])
    _sheet(wb, "Internal elements", ["Source", "Category", "Element", "Type", "Value", "Sensitivity"],
           [[e.source, e.label, e.element, e.dtype, e.value, e.sensitivity] for e in ds.live_elements()])
    if clean:
        _sheet(wb, "Audit trail", ["#", "Action", "Record", "Field", "Original", "New", "Reason", "Source", "By"],
               [[l["n"], l["action"], l["record"], l["field"], l["from"], l["to"], l["reason"], l["source"], l["by"]] for l in clean["log"]])
        _sheet(wb, "Escalations", ["Item", "Why", "Owner", "Due"], [[e["item"], e["why"], e["owner"], e["due"]] for e in clean["escalations"]])
    co, sk = (ctx or {}).get("collect"), (ctx or {}).get("seek")
    if co:
        _sheet(wb, "Collector", ["Output", "Status", "Evidence found", "Evidence groups", "Missing", "Could add"],
               [[c["output"], {"ok": "Covered", "part": "Partly covered", "none": "Not covered"}[c["status"]], c["hit"], c["total"],
                 "; ".join(c["missing"]), ", ".join(c["addable"])] for c in co["coverage"]])
    if sk:
        _sheet(wb, "Seeker", ["Attribute", "Status", "Values found", "Locations", "Requested from"],
               [[r["attribute"], {"ok": "Found", "multi": "Found (several)", "conf": "Values disagree", "indirect": "Partial match",
                                  "pending": "Requested", "miss": "Not found"}[r["status"]],
                 "; ".join(f"{v['value']} ×{v['count']}" for v in r["values"]), ", ".join(r["locations"]), ", ".join(r["requested_from"])]
                for r in sk["results"]])
    if assess:
        _sheet(wb, "Assess", ["Criterion", "Score", "Rating", "Basis", "Issues"],
               [[k, v["score"], v["rating"], v["basis"], len(v["issues"])] for k, v in assess["dims"].items()])
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
